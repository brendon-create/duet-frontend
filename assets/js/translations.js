/**
 * 套用語言到所有 data-i18n 元素
 * @param {string} lang - 'zh' 或 'en'
 */
window.applyLanguage = function(lang) {
    if (lang !== 'zh' && lang !== 'en') lang = 'zh';
    localStorage.setItem('duet_language', lang);

    const t = window.translations[lang];

    // 純文字替換
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (t[key] !== undefined) el.textContent = t[key];
    });

    // HTML 替換（用於含 <br>、<em> 等標籤的元素）
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.dataset.i18nHtml;
        if (t[key] !== undefined) el.innerHTML = t[key];
    });

    // placeholder 替換
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        if (t[key] !== undefined) el.placeholder = t[key];
    });

    // title/tooltip 替換
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.dataset.i18nTitle;
        if (t[key] !== undefined) el.title = t[key];
    });

    // lang attribute
    document.documentElement.lang = lang === 'zh' ? 'zh-TW' : 'en';

    // 更新所有語言切換按鈕文字
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
        btn.textContent = t['nav.lang'] || (lang === 'zh' ? 'EN' : '中文');
    });
};

/**
 * 初始化語言（讀 localStorage，預設中文）
 */
window.initLanguage = function() {
    const saved = localStorage.getItem('duet_language') || 'zh';
    window.applyLanguage(saved);
    return saved;
};

/**
 * 取得單一翻譯字串（供 JS 動態設定文字用）
 */
window.t = function(key) {
    const lang = localStorage.getItem('duet_language') || 'zh';
    return window.translations[lang]?.[key] ?? window.translations.zh[key] ?? key;
};

/**
 * 切換語言
 */
window.toggleLanguage = function() {
    const current = localStorage.getItem('duet_language') || 'zh';
    window.applyLanguage(current === 'zh' ? 'en' : 'zh');
};
